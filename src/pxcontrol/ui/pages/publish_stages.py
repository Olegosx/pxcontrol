"""Словарь стадий раздела «Публикация»: подписи, подсказки, значки.

Стадии жизни поста (ADR-0032) нужны и самим экранам раздела
(:mod:`publish_section`), и форме нового поста, которая тоже стадия, —
поэтому словарь живёт отдельным модулем: иначе форма и раздел
импортировали бы друг друга по кругу. Здесь только данные и чистые
функции над ними: ни одного виджета, всё проверяется тестом.
"""

from __future__ import annotations

from enum import StrEnum

from qfluentwidgets import FluentIcon


class PublishStage(StrEnum):
	"""Стадия жизни поста — пункт подменю раздела (ADR-0032, п. 1).

	Порядок объявления — порядок пути поста, он же порядок пунктов
	в навигации и порядок чтения: создание → ожидание у нас → ожидание
	на сервере Telegram. Значение — маршрутный ключ страницы
	(``objectName``), по нему навигация отличает пункты друг от друга.
	"""

	NEW_POST = "publish"
	QUEUE = "publish_queue"
	SCHEDULED = "publish_scheduled"


#: Подпись раздела в навигации — корень ветки подменю.
SECTION_TITLE = "Публикация"

#: Значок раздела в навигации.
SECTION_ICON = FluentIcon.SEND

#: Маршрутный ключ корня ветки. Своей страницы у него нет: корень —
#: заголовок ветки, стадии живут пунктами под ним.
SECTION_ROUTE_KEY = "publish_section"


def stage_title(stage: PublishStage) -> str:
	"""Подпись стадии: пункт навигации и заголовок её экрана."""
	return {
		PublishStage.NEW_POST: "Новый пост",
		PublishStage.QUEUE: "Очередь",
		PublishStage.SCHEDULED: "Отложено",
	}[stage]


def stage_hint(stage: PublishStage) -> str:
	"""Строка под заголовком экрана: чем эта стадия отличается от соседних.

	Разница между «Очередью» и «Отложено» неочевидна и важна: пост
	в очереди уйдёт только при запущенном приложении, а отложенную
	запись опубликует сервер Telegram сам (ADR-0010). Пока эти списки
	жили вкладками одной страницы, разница объяснялась один раз над
	обеими; у отдельных экранов каждый отвечает за себя.
	"""
	return {
		PublishStage.NEW_POST: (
			"Пост уходит в очередь отправки: форма освобождается сразу, "
			"а очередь показана ниже и целиком — на экране «Очередь»."
		),
		PublishStage.QUEUE: (
			"Посты ждут отправки в приложении — своей очереди или свободного "
			"слота отложек. Выключите приложение — они не уйдут."
		),
		PublishStage.SCHEDULED: (
			"Записи уже у сервера Telegram: он опубликует их сам, даже при "
			"выключенном компьютере. Список читается обходом сообществ."
		),
	}[stage]


def stage_icon(stage: PublishStage) -> FluentIcon:
	"""Значок пункта навигации для стадии."""
	return {
		PublishStage.NEW_POST: FluentIcon.EDIT,
		PublishStage.QUEUE: FluentIcon.ALIGNMENT,
		PublishStage.SCHEDULED: FluentIcon.CALENDAR,
	}[stage]
