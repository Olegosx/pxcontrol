"""Общие константы и геометрия целевого кадра (порт из makeVideo).

Размер итогового кадра считается в Python (:func:`scaled_size`), а не
фильтром ffmpeg с force_original_aspect_ratio: основное видео и кадр
заставки должны получить ровно одинаковые размеры — это требование
фильтра склейки xfade. Два независимых вписывания в ffmpeg могли давать
расхождение в размерах и валить обработку.

Разрешение задаётся ступенью (:data:`RESOLUTION_STEPS`) — числом строк
развёртки из обозначений вида «1080p» (это 1920×1080). Число ступени
присваивается короткой стороне кадра: у альбомной ориентации короткая —
высота, у книжной — ширина (вертикальный ролик 1080p — это 1080×1920).
Вторая сторона считается из пропорций исходника, поэтому отношение
сторон не меняется ни при каких условиях.
"""

#: Ступени разрешения: число строк развёртки, оно же — короткая сторона
#: итогового кадра. От HD до 4K UHD.
RESOLUTION_STEPS = (720, 1080, 1440, 2160)

#: Ступень по умолчанию — FullHD.
DEFAULT_RESOLUTION = 1080

# Формат пикселей для совместимости с большинством плееров и H.264.
TARGET_PIX_FMT = "yuv420p"

# Матрица преобразования RGB→YUV для вотермарка: обычное (не-HDR) видео
# размечается bt709 на любой ступени разрешения. Матрица по умолчанию
# в ffmpeg — bt601 (SD): из-за несовпадения с разметкой файла плеер
# сдвигал оттенки вотермарка.
TARGET_COLOR_MATRIX = "bt709"

# Кодирование результата (как в референсе makeVideo): H.264 + AAC.
VIDEO_CODEC = "libx264"
ENCODE_PRESET = "medium"
AUDIO_CODEC = "aac"
# Битрейт звука: число — для расчётов (рекомендация битрейта видео),
# строка — производная для аргумента ffmpeg (не наоборот: обратный разбор
# строки сломался бы молча при смене формата).
AUDIO_KBPS = 192
AUDIO_BITRATE = f"{AUDIO_KBPS}k"

# Запасное качество, когда битрейт не задан и ffprobe его не сообщил.
FALLBACK_CRF = "20"


def _even(value: float) -> int:
	"""Округляет сторону кадра до чётного числа пикселей (не меньше двух).

	Нечётных сторон не принимает H.264 в формате yuv420p. Нижняя граница
	страхует от вырожденного нуля на исходниках в пару пикселей: нулевая
	сторона дала бы дамп ffmpeg вместо понятной картины.
	"""
	return max(2, round(value / 2) * 2)


def scaled_size(width: int, height: int, target: int | None) -> tuple[int, int]:
	"""Размер итогового кадра для заданной ступени разрешения.

	Ведущая сторона — короткая: ей присваивается число ступени (у альбомного
	кадра это высота, у книжного — ширина). Вторая сторона считается из
	пропорций исходника, поэтому отношение сторон сохраняется. Округление
	сторон до чётных может увести пропорцию меньше чем на пиксель — этого
	не избежать, кодек нечётных сторон не принимает.

	Args:
		width: ширина исходного кадра в пикселях (отображаемая — флаг
			поворота учитывает :func:`~pxcontrol.engine.video.probe.probe_video`).
		height: высота исходного кадра в пикселях (отображаемая).
		target: ступень разрешения из :data:`RESOLUTION_STEPS`; None —
			«как в оригинале», кадр не масштабируется.

	Returns:
		Пара (ширина, высота) итогового кадра.

	Raises:
		ValueError: Размеры исходного кадра неположительны.
	"""
	if width <= 0 or height <= 0:
		raise ValueError(f"Недопустимые размеры кадра: {width}×{height}.")
	if target is None:
		return _even(width), _even(height)
	ratio = target / min(width, height)
	return _even(width * ratio), _even(height * ratio)


def is_upscale(width: int, height: int, target: int | None) -> bool:
	"""Приведёт ли ступень к увеличению кадра (апскейлу).

	Увеличение — когда число ступени больше короткой стороны исходника:
	масштаб у сторон общий, поэтому растут либо обе, либо ни одной.

	Args:
		width: ширина исходного кадра в пикселях.
		height: высота исходного кадра в пикселях.
		target: ступень разрешения; None («как в оригинале») не увеличивает.

	Returns:
		True, если итоговый кадр крупнее исходного.
	"""
	return target is not None and target > min(width, height)
