"""Возможности сообщества и выбор маршрута отправки (ADR-0031).

Маршрутов у поста несколько, и выбор между ними не дело вкуса. Правило
одно: **по умолчанию — технически простейший маршрут из тех, что дают
нужный исход**, а усложнение допускается только по названной причине
(бот не может залить такой файл, в группе нет права правки, нужна
серверная отложка). Простота считается числом шагов и объёмом
состояния: один вызов без состояния проще двух.

Модуль чистый: ни сети, ни базы, ни моделей. Так лестница выбора
проверяется тестами целиком и живёт одной точкой, а не условиями,
размазанными по сервисам (требование ADR-0031, п. 2a). Полная картина
маршрутов с матрицей комплектаций — `docs/03-modules/publishing-routes.md`.

Здесь описаны только те маршруты, что уже работают. Склад (Р3),
отложенная пересылка (Р5) и кнопки у отложенных записей (Р2 в её дорогой
половине) появятся следующими этапами — до тех пор их случаи честно
объявляются недоступными, а не подменяются похожими.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum

from pxcontrol.engine.telegram.types import BOT_MAX_FILE_BYTES, CommunityKind, limit_mb


@dataclass(frozen=True)
class PublishCapabilities:
	"""Возможности публикации сообщества (из способов администрирования).

	Attributes:
		userbot: полный набор — любые типы, до 2 ГБ, «сейчас» и отложенные.
		bot: запасной путь — текст и медиа до 50 МБ, только «сейчас».
			Он же означает «кнопки возможны»: ставит их только бот
			(ADR-0031), и своему посту он ставит их всегда.
		markup_edit: бот может дорисовать кнопки к посту **публикателя**
			(право канала ``edit_messages``, ADR-0031). Без него кнопки
			остаются только у постов, которые бот отправляет сам, —
			то есть недоступны крупным файлам.
	"""

	userbot: bool
	bot: bool
	markup_edit: bool = False


def publish_capabilities(
	bot_assigned: bool, userbot_assigned: bool, *, markup_edit: bool = False
) -> PublishCapabilities:
	"""Возможности публикации по публикаторам сообщества.

	Единственный источник правды для движка и интерфейса; приоритет
	транспорта — MTProto (ADR-0011), userbot-путь доступен при
	назначенном публикаторе по умолчанию (ADR-0022). Приостановленный
	публикатор (ADR-0029) вызывающей стороной считается неназначенным —
	см. ``community_capabilities`` и ``CommunityDto.capabilities``.
	"""
	return PublishCapabilities(userbot=userbot_assigned, bot=bot_assigned, markup_edit=markup_edit)


class PublishRoute(StrEnum):
	"""Каким путём уходит пост.

	Значения совпадают с маршрутами документа `publishing-routes.md`:
	``USERBOT`` — Р1, ``BOT`` — Р4, ``USERBOT_MARKUP`` — Р2 в дешёвой
	половине («сейчас»: номер поста известен из ответа, обещание хранить
	не нужно).
	"""

	USERBOT = "userbot"  # Р1: публикатор отправляет сам, кнопок нет
	BOT = "bot"  # Р4: бот отправляет сам — один вызов, кнопки сразу
	USERBOT_MARKUP = "userbot_markup"  # Р2: публикатор отправил, бот дорисовал


def markup_blocker(
	caps: PublishCapabilities,
	*,
	title: str,
	kind: CommunityKind,
	scheduled: bool,
	media_over_bot_limit: bool,
) -> str | None:
	"""Что мешает поставить кнопки этому посту (None — ничего).

	Одна точка правды на две стороны: движок по ней отклоняет черновик,
	интерфейс — объясняет, почему кнопки недоступны, вместо молчаливо
	серой кнопки.

	Args:
		caps: возможности сообщества.
		title: название сообщества — для текста человеку.
		kind: вид сообщества (в группе правка чужого невозможна).
		scheduled: пост отложенный (кнопки у отложек — следующий этап).
		media_over_bot_limit: файл больше лимита бота (50 МБ).

	Returns:
		Текст причины для человека или None, если кнопки возможны.
	"""
	if not caps.bot:
		return (
			f"Кнопки ставит только бот, а у «{title}» его нет. Назначьте бота "
			"администратором сообщества на его странице."
		)
	if scheduled:
		# честное «пока»: серверную отложку публикует Telegram, и кнопки
		# к ней можно применить лишь после выхода поста — эта работа
		# (опознание вышедшего поста) появится следующим этапом
		return (
			"Кнопки у отложенных постов пока не поддерживаются — "
			"отправьте пост «сейчас» или снимите кнопки."
		)
	if not media_over_bot_limit:
		return None  # бот отправит сам — кнопки будут с первой секунды
	if kind is not CommunityKind.CHANNEL:
		return (
			f"В группе «{title}» кнопки возможны только у постов, которые "
			f"отправляет сам бот, а файл больше {limit_mb(BOT_MAX_FILE_BYTES)} МБ."
		)
	if not caps.markup_edit:
		return (
			f"Файл больше {limit_mb(BOT_MAX_FILE_BYTES)} МБ, поэтому пост отправит "
			f"публикатор, а кнопки к нему дорисовывает бот — но у бота «{title}» "
			"нет права изменять сообщения. Выдайте право в настройках "
			"администратора канала и перепроверьте доступы."
		)
	if not caps.userbot:
		return (
			f"Файл больше {limit_mb(BOT_MAX_FILE_BYTES)} МБ — такой пост отправляет "
			f"публикатор, а у «{title}» его нет."
		)
	return None


def choose_route(
	caps: PublishCapabilities, *, with_markup: bool, media_over_bot_limit: bool
) -> PublishRoute:
	"""Маршрут отправки по содержимому поста (лестница простоты).

	Предусловие: препятствий нет — их проверяет :func:`markup_blocker`
	(кнопки) и подготовка публикации (публикатор, пределы). Здесь —
	только выбор из возможного.

	Порядок лестницы:

	1. кнопок нет → публикатор, если он есть (ADR-0011), иначе бот;
	2. кнопки и бот справится с файлом → бот отправляет сам: один вызов,
		никакого состояния, кнопки с первой секунды;
	3. кнопки и файл больше лимита бота → отправляет публикатор,
		бот дорисовывает разметку.
	"""
	if not with_markup:
		return PublishRoute.USERBOT if caps.userbot else PublishRoute.BOT
	if not media_over_bot_limit:
		return PublishRoute.BOT
	return PublishRoute.USERBOT_MARKUP


def route_uses_userbot(route: PublishRoute) -> bool:
	"""Отправляет ли пост публикатор (а не бот) — от этого зависят пределы.

	У бота не бывает подписки: его пределы длины и размера файла всегда
	базовые, а у публикатора — по Premium его аккаунта (ADR-0019).
	"""
	return route is not PublishRoute.BOT
