"""Периодическая фоновая задача движка (ADR-0020).

Три дозора устроены одинаково: проход, пауза, снова — до остановки.
Это опрос статистики сообществ (ADR-0027), дозор обещанных клавиатур
(ADR-0031) и сброс записей активности (ADR-0030). У всех троих одни
и те же обязанности, и написаны они были трижды почти дословно —
вместе с собственной константой страховочного срока у каждого.

Правило проекта — обобщать на третьем потребителе (ADR-0014 → ADR-0025);
для очередей заданий оно исполнено, и здесь исполняется для дозоров.
Предметное (что делает проход) остаётся у сервиса: каркас знает только,
как жить по тикам и как честно умереть.

Дозор слотов очереди отправки сюда **не входит намеренно**: он живёт,
только пока есть ждущие посты, и сам завершается, когда их не осталось,
а интервал у него плавающий — настройка вместе со сроком ближайшего
поста режима «кнопки важнее». Общего у него с этими тремя — одно лишь
слово «фоновая»: подводить их под один каркас значило бы получить
абстракцию, у которой половина параметров нужна одному потребителю.
"""

from __future__ import annotations

import asyncio
import contextlib
import logging
from collections.abc import Awaitable, Callable

logger = logging.getLogger(__name__)

#: Страховка кооперативной остановки: столько ждём задачу после того,
#: как взведено событие остановки. Штатно она выходит мгновенно —
#: пауза между проходами прерывается тем же событием.
DEFAULT_SHUTDOWN_TIMEOUT_S = 10.0


class PeriodicTask:
	"""Фоновая задача «проход раз в интервал» с кооперативной остановкой.

	Три обязанности, ради которых каркас и заведён:

	- **проход не убивает задачу.** Исключение уходит в журнал
		с трассировкой, а дозор живёт дальше: иначе один неудачный проход
		тихо лишал бы приложение статистики или кнопок до перезапуска;
	- **пауза прерывается остановкой.** Ждём не ``sleep``, а событие
		остановки с пределом по времени: ``shutdown`` не досиживает
		чужой интервал (ADR-0020);
	- **остановка честная.** Взводим событие, ждём задачу в пределах
		страховочного срока и только потом отпускаем; не успевшую
		отменяем как последнее средство.

	Проход зовётся сразу при запуске, до первой паузы: приложение
	открыли — данные нужны сейчас, а не через тик.
	"""

	def __init__(
		self,
		run: Callable[[], Awaitable[object]],
		*,
		name: str,
		interval_s: float,
		shutdown_timeout_s: float = DEFAULT_SHUTDOWN_TIMEOUT_S,
	) -> None:
		"""Готовит задачу (не запуская её).

		Args:
			run: один проход дозора.
			name: имя для журнала — им названа задача в записи о сбое.
			interval_s: пауза между проходами.
			shutdown_timeout_s: сколько ждать задачу при остановке.
		"""
		self._run = run
		self._name = name
		self._interval_s = interval_s
		self._shutdown_timeout_s = shutdown_timeout_s
		self._stop = asyncio.Event()
		self._task: asyncio.Task[None] | None = None

	@property
	def stopping(self) -> bool:
		"""Движок останавливается — длинный проход обязан выйти сам.

		Проход, идущий по многим сообществам или обещаниям, спрашивает
		это между шагами: прервать его снаружи нельзя (ADR-0020),
		прекратить работу может только тот, кто её ведёт.
		"""
		return self._stop.is_set()

	def start(self) -> None:
		"""Запускает задачу, если она ещё не идёт (идемпотентно)."""
		if self._task is None or self._task.done():
			self._stop.clear()
			self._task = asyncio.create_task(self._loop())

	async def shutdown(self) -> None:
		"""Гасит задачу кооперативно и дожидается её конца."""
		self._stop.set()
		if self._task is not None:
			with contextlib.suppress(TimeoutError, asyncio.CancelledError):
				await asyncio.wait_for(self._task, timeout=self._shutdown_timeout_s)
			self._task = None

	async def _loop(self) -> None:
		"""Проход, пауза, снова — пока не попросят остановиться."""
		while not self._stop.is_set():
			try:
				await self._run()
			except Exception:  # noqa: BLE001 — дозор не должен умирать
				logger.exception("%s: проход не удался.", self._name)
			with contextlib.suppress(TimeoutError):
				await asyncio.wait_for(self._stop.wait(), timeout=self._interval_s)
